#!/usr/bin/env bash
set -Eeuo pipefail

PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_DIR=/etc/ncc-server
ENV_FILE="$CONFIG_DIR/ncc-server.env"
CADDYFILE="$CONFIG_DIR/Caddyfile"
SERVICE_RECORD_ID="${1:-}"

die() { echo "Error: $*" >&2; exit 1; }

[[ "$(id -u)" -eq 0 ]] || die 'run with sudo or as root'
[[ "$SERVICE_RECORD_ID" =~ ^[1-9][0-9]*$ ]] || die 'pass the numeric sidecar service record ID'
[[ -f "$ENV_FILE" ]] || die "missing $ENV_FILE; run make install first"
command -v caddy >/dev/null || die 'Caddy is not installed'
command -v openssl >/dev/null || die 'openssl is required'
command -v curl >/dev/null || die 'curl is required'
id ncc-sidecar >/dev/null 2>&1 || die 'ncc-sidecar service account is missing'
getent group caddy >/dev/null || die 'caddy group is missing'

CERT_DIR="/opt/ncc-sidecar/certs/$SERVICE_RECORD_ID"
CERT_PATH="$CERT_DIR/server.crt"
KEY_PATH="$CERT_DIR/server.key"
[[ -s "$CERT_PATH" && -s "$KEY_PATH" ]] || die "sidecar certificate not found under $CERT_DIR; let the configured service publish once first"

cert_pub="$(openssl x509 -in "$CERT_PATH" -pubkey -noout | openssl pkey -pubin -outform DER 2>/dev/null | sha256sum | awk '{print $1}')"
key_pub="$(openssl pkey -in "$KEY_PATH" -pubout -outform DER 2>/dev/null | sha256sum | awk '{print $1}')"
[[ -n "$cert_pub" && "$cert_pub" == "$key_pub" ]] || die 'certificate and private key do not match'

# Caddy and the sidecar share the generated key through a dedicated group.
# The service retains ownership, and the setgid directory preserves caddy as
# the group for a key regenerated by ncc-sidecar.
chown ncc-sidecar:caddy "$CERT_DIR"
chmod 2750 "$CERT_DIR"
chown ncc-sidecar:caddy "$CERT_PATH" "$KEY_PATH"
chmod 0640 "$CERT_PATH" "$KEY_PATH"

install -d -o root -g root -m 0755 /etc/systemd/system/ncc-sidecar.service.d
install -o root -g root -m 0644 "$PROJECT_DIR/systemd/ncc-sidecar.conf" \
  /etc/systemd/system/ncc-sidecar.service.d/ncc-server.conf
systemctl daemon-reload
systemctl restart ncc-sidecar.service

backup_dir="$(mktemp -d /tmp/ncc-server-tls.XXXXXX)"
cp -a "$ENV_FILE" "$backup_dir/ncc-server.env"
cp -a "$CADDYFILE" "$backup_dir/Caddyfile"
restore() {
  cp -a "$backup_dir/ncc-server.env" "$ENV_FILE"
  cp -a "$backup_dir/Caddyfile" "$CADDYFILE"
  systemctl restart caddy.service || true
  rm -rf "$backup_dir"
}

set_env() {
  local key="$1" value="$2"
  if grep -q "^${key}=" "$ENV_FILE"; then
    sed -i "s|^${key}=.*|${key}=${value}|" "$ENV_FILE"
  else
    printf '%s=%s\n' "$key" "$value" >> "$ENV_FILE"
  fi
}

set_env CONTENT_TLS_PORT 8443
set_env TLS_CERT_PATH "$CERT_PATH"
set_env TLS_KEY_PATH "$KEY_PATH"
cp "$PROJECT_DIR/caddy/Caddyfile.tls" "$CADDYFILE"
chown root:root "$ENV_FILE" "$CADDYFILE"
chmod 0600 "$ENV_FILE"
chmod 0644 "$CADDYFILE"

# Caddy expands {$NAME} from its systemd EnvironmentFile. Load that same file
# while validating the selected config before restarting the live service.
set -a
# shellcheck disable=SC1090
source "$ENV_FILE"
set +a
if ! caddy validate --adapter caddyfile --config "$CADDYFILE"; then
  restore
  die 'Caddy rejected the TLS configuration; previous config restored'
fi
if ! systemctl restart caddy.service; then
  restore
  die 'Caddy failed to start with TLS; previous config restored'
fi
if ! curl --fail --silent --show-error --insecure --max-time 10 "https://127.0.0.1:${CONTENT_TLS_PORT}/" >/dev/null; then
  restore
  die 'HTTPS health check failed; previous config restored'
fi
rm -rf "$backup_dir"

fingerprint="$(openssl x509 -in "$CERT_PATH" -pubkey -noout | openssl pkey -pubin -outform DER 2>/dev/null | openssl dgst -sha256 -binary | openssl base64 -A | tr '+/' '-_' | tr -d '=')"
echo "Pinned HTTPS is active on port ${CONTENT_TLS_PORT}."
echo "Certificate SPKI fingerprint (sidecar endpoint k): $fingerprint"
echo "Configure this sidecar service to prefer https on port ${CONTENT_TLS_PORT}, then force a publish."

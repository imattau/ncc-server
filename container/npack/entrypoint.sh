#!/bin/sh
# Write the npack config from the bundle's environment, then run npackd.
#
# npackd keeps its catalogue and package state under XDG_DATA_HOME, which is
# a volume in the Compose service. The sidecar only ever reads the daemon over
# the Unix socket; nothing here installs packages into the host.
set -eu

mkdir -p "${XDG_CONFIG_HOME:-/data/config}/npack" "${XDG_RUNTIME_DIR:-/run/npack}"

config="${XDG_CONFIG_HOME:-/data/config}/npack/config.toml"
relays="${NPACK_RELAYS:-wss://relay.damus.io,wss://nos.lol,wss://relay.primal.net}"
blossom="${NPACK_BLOSSOM_SERVERS:-https://blossom.primal.net,https://cdn.satellite.earth}"

{
  echo '# Generated by the NCC Server npack container. Edit NPACK_* env instead.'
  echo '[network]'
  echo 'relays = ['
  printf '%s\n' "$relays" | tr ',' '\n' | while IFS= read -r relay; do
    if [ -n "$relay" ]; then printf '  "%s",\n' "$relay"; fi
  done
  echo ']'
  echo
  echo '[storage]'
  echo 'blossom = ['
  printf '%s\n' "$blossom" | tr ',' '\n' | while IFS= read -r server; do
    if [ -n "$server" ]; then printf '  "%s",\n' "$server"; fi
  done
  echo ']'
} > "$config"

socket="${NPACK_SOCKET:-/run/npack/npackd.sock}"
exec npack daemon --socket "$socket"

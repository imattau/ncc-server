import test from 'node:test';
import assert from 'node:assert/strict';

import {
  MAX_CADDY_SITES,
  normalizeCaddySites,
  normalizePublicDomain,
  renderCaddySites,
} from '../caddy-sites.mjs';

const PUBKEY = 'a'.repeat(64);

function site(extra = {}) {
  return {
    serviceId: 'ditto',
    domain: 'ditto.example.com',
    target: {
      kind: 'proxy',
      dial: '127.0.0.1:3210',
      host: '203.0.113.10',
      body: 'app',
    },
    ...extra,
  };
}

test('public domains: normalises a normal FQDN', () => {
  assert.equal(normalizePublicDomain(' Ditto.Example.COM. '), 'ditto.example.com');
  assert.equal(normalizePublicDomain('xn--bcher-kva.com'), 'xn--bcher-kva.com');
  assert.equal(normalizePublicDomain('bücher.com'), 'xn--bcher-kva.com');
});

test('public domains: rejects anything that cannot be a public DNS name', () => {
  for (const value of [
    '',
    'localhost',
    'example',
    '127.0.0.1',
    '203.0.113.10',
    'https://example.com',
    'example.com/path',
    'example.com:443',
    '*.example.com',
    'example.com?x=1',
    'example.local',
    'example.internal',
    'example.test',
    'example.invalid',
    'example.example',
    'bad_name.example',
    '-bad.example',
    'bad-.example',
  ]) {
    assert.equal(normalizePublicDomain(value), null, String(value));
  }
});

test('render: common public HTTPS front door uses a Host override', () => {
  const output = renderCaddySites({ sites: [site()] });
  assert.match(output, /https:\/\/ditto\.example\.com \{/);
  assert.match(output, /http:\/\/ditto\.example\.com \{/);
  assert.match(output, /redir https:\/\/\{host\}\{uri\} permanent/);
  assert.match(output, /reverse_proxy 127\.0\.0\.1:3210 \{/);
  assert.match(output, /header_up Host 203\.0\.113\.10/);
  assert.match(output, /import ncc_body_app/);
  assert.match(output, /import cors_response/);
});

test('render: custom proxy keeps the requested Host and can add real-IP', () => {
  const output = renderCaddySites({
    sites: [site({
      serviceId: 'files',
      target: {
        kind: 'proxy',
        dial: '127.0.0.1:3300',
        body: 'small',
        realIp: true,
      },
    })],
  });
  assert.doesNotMatch(output, /header_up Host/);
  assert.match(output, /header_up X-Real-IP \{remote_host\}/);
  assert.match(output, /import ncc_body_small/);
});

test('render: search splits UI and API paths', () => {
  const output = renderCaddySites({
    sites: [site({
      serviceId: 'search',
      target: {
        kind: 'search',
        ui: '127.0.0.1:3220',
        api: '127.0.0.1:3230',
        host: '203.0.113.10',
        body: 'small',
      },
    })],
  });
  assert.match(output, /handle \/search\* \{/);
  assert.match(output, /handle \/status\* \{/);
  assert.match(output, /reverse_proxy 127\.0\.0\.1:3230/);
  assert.match(output, /reverse_proxy 127\.0\.0\.1:3220/);
});

test('render: static web serves the welcome page and public visibility only', () => {
  const output = renderCaddySites({
    operatorPubkey: PUBKEY,
    sites: [site({
      serviceId: 'web',
      domain: 'example.com',
      target: { kind: 'static', body: 'small' },
    })],
  });
  assert.match(output, /root \* \/srv\/ncc-server\/public/);
  assert.match(output, /handle \/ncc-config\.json/);
  assert.match(output, /"panelApi":"https:\/\/example\.com\/ncc-api"/);
  assert.match(output, /handle \/ncc-api\/public\/visibility/);
  assert.doesNotMatch(output, /import ncc_admin_api/);
});

test('render: admin panel uses a domain-aware panel API', () => {
  const output = renderCaddySites({
    operatorPubkey: PUBKEY,
    sites: [site({
      serviceId: 'admin',
      domain: 'admin.example.com',
      target: { kind: 'admin', body: 'small' },
    })],
  });
  assert.match(output, /root \* \/srv\/ncc-server\/admin-panel/);
  assert.match(output, /import ncc_admin_api/);
  assert.match(output, /"panelApi":"https:\/\/admin\.example\.com\/ncc-api"/);
  assert.match(output, /url=\/admin/);
});

test('render: no sites produces a comment-only fragment', () => {
  const output = renderCaddySites({ sites: [] });
  assert.match(output, /Generated by the NCC admin panel node-agent/);
  assert.doesNotMatch(output, /https:\/\//);
});

test('normalise: rejects duplicate domains', () => {
  assert.throws(
    () => normalizeCaddySites({ sites: [site(), site({ serviceId: 'search' })] }),
    /duplicate public domain/,
  );
});

test('normalise: rejects uploads outside loopback and unknown kinds', () => {
  assert.throws(
    () => normalizeCaddySites({ sites: [site({ target: { kind: 'proxy', dial: '10.0.0.2:80' } })] }),
    /127\.0\.0\.1/,
  );
  assert.throws(
    () => normalizeCaddySites({ sites: [site({ target: { kind: 'raw', body: 'small' } })] }),
    /unsupported target kind/,
  );
  assert.throws(
    () => normalizeCaddySites({ sites: [site({ target: { kind: 'proxy', dial: '127.0.0.1:70000' } })] }),
    /invalid port/,
  );
});

test('normalise: static and admin sites require an operator pubkey', () => {
  assert.throws(
    () => normalizeCaddySites({ sites: [site({ target: { kind: 'static' } })] }),
    /operatorPubkey is required/,
  );
  assert.throws(
    () => normalizeCaddySites({
      operatorPubkey: 'nope',
      sites: [site({ target: { kind: 'admin' } })],
    }),
    /64-character hex/,
  );
});

test('normalise: caps the number of domains', () => {
  const sites = Array.from({ length: MAX_CADDY_SITES + 1 }, (_, index) => site({
    serviceId: `svc-${index}`,
    domain: `svc-${index}.example.com`,
  }));
  assert.throws(() => normalizeCaddySites({ sites }), /at most/);
});
